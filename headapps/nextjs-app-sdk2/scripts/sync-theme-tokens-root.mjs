#!/usr/bin/env node
/**
 * Regenerates src/assets/themes/_theme-tokens-root.css from _theme-tokens.css.
 *
 * Why this exists
 * ---------------
 * The Tailwind v4 @theme block in _theme-tokens.css maps each token to another
 * CSS variable, e.g.
 *
 *   @theme {
 *     --color-component-alert-bg-priority: var(--component-alert-bg-priority);
 *   }
 *
 * Tailwind v4 wants to register every @theme variable with @property for
 * proper inheritance, but @property requires a literal initial value. Values
 * that contain var(...) have no literal initial value, so Tailwind falls back
 * to an @supports polyfill that only runs on older Safari/Firefox builds.
 *
 * Modern Chrome/Safari/Firefox therefore never receive a declaration for the
 * alias, and the Tailwind utility (.bg-component-alert-bg-priority, etc.)
 * renders transparent. We also can't declare them at :root because the
 * underlying --component-* / --spacing-* tokens are only defined inside the
 * brand class (.BrandsBrandX, etc.), so var() substitution at :root fails and
 * the property becomes invalid-at-computed-value-time.
 *
 * The fix is to emit the same declarations on .brand-root, which is applied by
 * BrandAndThemeProvider to the same element that carries the brand + theme
 * classes. At that element both sides of the var() exist, so substitution
 * succeeds and descendants inherit a resolved value.
 *
 * Run this script whenever _theme-tokens.css is regenerated from Figma.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(__dirname, '../src/assets/themes/_theme-tokens.css');
const DEST = resolve(__dirname, '../src/assets/themes/_theme-tokens-root.css');

const contents = readFileSync(SRC, 'utf8');

const decls = contents
  .split('\n')
  .filter((line) => /^\s*--[\w-]+\s*:/.test(line))
  .join('\n');

if (!decls.length) {
  console.error('No custom property declarations found in', SRC);
  process.exit(1);
}

const header = `/* AUTO-GENERATED by scripts/sync-theme-tokens-root.mjs from _theme-tokens.css.
   Do not edit by hand — re-run \`npm run sync:theme-root\` after regenerating
   tokens from Figma. See the script header for the full rationale. */\n`;

const output = `${header}.brand-root {\n${decls}\n}\n`;
writeFileSync(DEST, output);

const count = decls.split('\n').length;
console.log(`Wrote ${count} declarations to ${DEST}`);
